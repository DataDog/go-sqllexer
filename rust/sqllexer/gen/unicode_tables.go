//go:build ignore

// Generates the Unicode range tables used by the Rust lexer.
//
// The Rust core must classify runes exactly like the Go lexer does, and Rust's
// char::is_alphabetic is the Unicode Alphabetic property while Go's
// unicode.IsLetter is category L — they disagree on a few thousand code points.
// Deriving the tables from the Go runtime that the oracle itself uses removes
// that class of mismatch, including future Unicode version drift.
//
// Usage: go run gen/unicode_tables.go > src/unicode_tables.rs
package main

import (
	"fmt"
	"os"
	"unicode"
)

type span struct{ lo, hi rune }

func ranges(pred func(rune) bool) []span {
	var out []span
	var cur span
	open := false
	for r := rune(128); r <= unicode.MaxRune; r++ {
		if pred(r) {
			if open && cur.hi == r-1 {
				cur.hi = r
				continue
			}
			if open {
				out = append(out, cur)
			}
			cur, open = span{r, r}, true
			continue
		}
	}
	if open {
		out = append(out, cur)
	}
	return out
}

func emit(w *os.File, name string, spans []span) {
	fmt.Fprintf(w, "pub(crate) static %s: [(u32, u32); %d] = [\n", name, len(spans))
	for _, s := range spans {
		fmt.Fprintf(w, "    (0x%04X, 0x%04X),\n", s.lo, s.hi)
	}
	fmt.Fprintf(w, "];\n\n")
}

func main() {
	w := os.Stdout
	fmt.Fprintf(w, "// Code generated by gen/unicode_tables.go; DO NOT EDIT.\n")
	fmt.Fprintf(w, "// Ranges of non-ASCII code points for which Go's unicode.IsLetter and\n")
	fmt.Fprintf(w, "// unicode.IsNumber report true, so the Rust lexer classifies identifiers\n")
	fmt.Fprintf(w, "// exactly like the Go implementation it must stay compatible with.\n\n")
	emit(w, "LETTER_RANGES", ranges(unicode.IsLetter))
	emit(w, "NUMBER_RANGES", ranges(unicode.IsNumber))
	// strings.TrimSpace trims every Unicode space, not just ASCII blanks, and it
	// is applied to the final obfuscated and normalized output.
	emit(w, "SPACE_RANGES", ranges(unicode.IsSpace))
}
